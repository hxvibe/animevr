// 3단계: 정점·UV·법선 + 텍스처 → GLB (WebP · 양자화 · meshopt)
import { Document, NodeIO } from '@gltf-transform/core';
import { ALL_EXTENSIONS, EXTMeshoptCompression } from '@gltf-transform/extensions';
import { weld, quantize, reorder, textureCompress, prune } from '@gltf-transform/functions';
import { MeshoptEncoder } from 'meshoptimizer';
import sharp from 'sharp';
import fs from 'fs';
const [dir, name, out, title] = process.argv.slice(2);
await MeshoptEncoder.ready;
const rd = (k) => new Float32Array(fs.readFileSync(`${dir}/${name}.out.${k}.bin`).buffer.slice(0));
const doc = new Document();
const buf = doc.createBuffer();
const pos = doc.createAccessor().setType('VEC3').setArray(rd('pos')).setBuffer(buf);
const nrm = doc.createAccessor().setType('VEC3').setArray(rd('nrm')).setBuffer(buf);
const uv = doc.createAccessor().setType('VEC2').setArray(rd('uv')).setBuffer(buf);
const n = pos.getCount();
const idx = doc.createAccessor().setType('SCALAR').setArray(new Uint32Array(n).map((_, i) => i)).setBuffer(buf);
const tex = (f) => doc.createTexture(f).setImage(fs.readFileSync(`${dir}/${name}_${f}.png`)).setMimeType('image/png');
const mat = doc.createMaterial(title).setBaseColorTexture(tex('color')).setMetallicRoughnessTexture(tex('orm')).setNormalTexture(tex('normal')).setRoughnessFactor(1).setMetallicFactor(1);
const prim = doc.createPrimitive().setAttribute('POSITION', pos).setAttribute('NORMAL', nrm).setAttribute('TEXCOORD_0', uv).setIndices(idx).setMaterial(mat);
const mesh = doc.createMesh(title).addPrimitive(prim);
const node = doc.createNode(title).setMesh(mesh);
doc.createScene().addChild(node);
const meta = JSON.parse(fs.readFileSync(`${dir}/${name}.meta.json`));
node.setExtras(meta);
await doc.transform(weld(), textureCompress({ encoder: sharp, targetFormat: 'webp', quality: 84 }), reorder({ encoder: MeshoptEncoder }), quantize(), prune());
doc.createExtension(EXTMeshoptCompression).setRequired(true).setEncoderOptions({ method: EXTMeshoptCompression.EncoderMethod.QUANTIZE });
const io = new NodeIO().registerExtensions(ALL_EXTENSIONS).registerDependencies({ 'meshopt.encoder': MeshoptEncoder });
await io.write(out, doc);
console.log(out, (fs.statSync(out).size / 1024).toFixed(0) + 'KB', 'verts after weld', doc.getRoot().listAccessors()[0].getCount());
